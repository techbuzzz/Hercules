    [Fact]
    public async Task MeshAuditService_LogOutboundDelegationAsync_InvokesAllEnabledSinks()
    {
        // Mock.Of returns default(bool)=false for IsEnabled, so set it explicitly via Mock.Get
        var sink1 = Mock.Of<IAuditSink>();
        var sink2 = Mock.Of<IAuditSink>();
        Mock.Get(sink1).SetupGet(s => s.IsEnabled).Returns(true);
        Mock.Get(sink2).SetupGet(s => s.IsEnabled).Returns(true);
        var loggerMock = new Mock<ILogger<MeshAuditService>>();
        var cfg = DefaultConfig();
        var svc = new MeshAuditService(new[] { sink1, sink2 }, cfg, loggerMock.Object);

        var envelope = IntentEnvelope.Create(
            "req-001", "agent-a", "csharp-refactor", """{"file":"foo.cs"}""",
            recipient: "agent-b");
        var transportResult = TransportResult.Ok(
            IntentResponse.Ok("req-001", "agent-b", "done"), 150, TransportKind.Http);

        await svc.LogOutboundDelegationAsync(
            envelope, "agent-a", "agent-b", transportResult,
            "Allowed", null, DataClassification.Internal);

        Mock.Get(sink1).Verify(s => s.WriteAsync(It.IsAny<InterAgentAuditRecord>(), It.IsAny<CancellationToken>()), Times.Once);
        Mock.Get(sink2).Verify(s => s.WriteAsync(It.IsAny<InterAgentAuditRecord>(), It.IsAny<CancellationToken>()), Times.Once);
    }

