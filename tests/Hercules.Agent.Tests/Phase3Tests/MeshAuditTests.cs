    [Fact]
    public void MeshAuditConfig_Defaults_AreSane()
    {
        var cfg = new MeshAuditConfig();

        Assert.True(cfg.Enabled);
        Assert.True(cfg.SerilogSinkEnabled);
        Assert.True(cfg.OpenTelemetrySinkEnabled);
        Assert.False(cfg.FileSinkEnabled);
        Assert.Equal("mesh-audit", cfg.FileSinkDirectory);
