    [Fact]
    public async Task FileMeshAuditSink_WriteAsync_CreatesJsonlFile()
    {
        var tempDir = Path.Combine(Path.GetTempPath(), $"mesh-audit-test-{Guid.NewGuid():N}");
        Directory.CreateDirectory(tempDir);
        var loggerMock = new Mock<ILogger<FileMeshAuditSink>>();
        var sink = new FileMeshAuditSink(tempDir, loggerMock.Object);
        var record = MakeRecord("outbound_delegation");

        try
        {
            await sink.WriteAsync(record);

            var files = Directory.GetFiles(tempDir, "mesh-audit-*.jsonl");
            Assert.Single(files);

            var lines = await File.ReadAllLinesAsync(files[0]);
            Assert.Single(lines);
            Assert.Contains("\"event_type\":\"outbound_delegation\"", lines[0]);
        }
        finally
        {
            sink.Dispose();
            try { if (Directory.Exists(tempDir)) Directory.Delete(tempDir, true); } catch { /* best effort */ }
        }
    }

