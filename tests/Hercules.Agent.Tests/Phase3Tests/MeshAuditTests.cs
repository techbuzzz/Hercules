                IntentEnvelope.Create($"req-{i}", "a", "intent", "{}", recipient: "b"),
                "a", "b",
                TransportResult.Ok(IntentResponse.Ok($"req-{i}", "b", "ok"), 10, TransportKind.Http),
                "Allowed", null, DataClassification.Public);
